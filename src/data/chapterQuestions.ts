const BOOK_OFFSET: Record<GospelKey, number> = {
  matthew: 1,
  mark: 2,
  luke: 0,
  john: 1,
};

export function getChapterQuestion(book: GospelKey, chapter: number): ChapterQuestion {
  const key = `${book}-${chapter}`;
  const raw = CHAPTER_QUESTIONS[key] || {
    questionAr: 'هل قرأت هذا الأصحاح بتأمل وتركيز؟',
    optionsAr: ['نعم، قرأت الأصحاح بالكامل', 'لم أبدأ القراءة بعد', 'سأقرأه لاحقاً'],
    questionEn: 'Did you read this chapter attentively?',
    optionsEn: ['Yes, I read the whole chapter', 'Not yet', 'I will read it later'],
    correctIndex: 0,
  };

  // Deterministically rotate choices so the correct option varies across A, B, and C
  const shift = (BOOK_OFFSET[book] + chapter) % raw.optionsAr.length;
  if (shift === 0) return raw;

  const rotate = <T,>(arr: T[]): T[] =>
    arr.map((_, i) => arr[(i - shift + arr.length) % arr.length]);

  return {
    ...raw,
    optionsAr: rotate(raw.optionsAr),
    optionsEn: rotate(raw.optionsEn),
    correctIndex: (raw.correctIndex + shift) % raw.optionsAr.length,
  };
}
